let currentLang = localStorage.getItem("siteLang") || "tr";
let activeProjFilter = "all";
let activeBlogCat = "all";
let activeBlogTag = "all";

function toggleLanguage() {
  currentLang = currentLang === "tr" ? "en" : "tr";
  localStorage.setItem("siteLang", currentLang);
  applyAll();
}

function toggleMobileMenu() {
  document.getElementById("mobile-menu").classList.toggle("hidden");
}

function applyAll() {
  document.documentElement.lang = currentLang;
  const toggleBtn = document.getElementById("lang-toggle");
  if (toggleBtn) toggleBtn.textContent = currentLang === "tr" ? "EN" : "TR";

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (i18n[currentLang][key]) el.textContent = i18n[currentLang][key];
  });

  const path = window.location.pathname.split("/").pop() || "index.html";
  document.querySelectorAll("[data-nav]").forEach(link => {
    if (link.getAttribute("data-nav") === path) link.classList.add("nav-active");
  });

  renderHome();
  renderProjects();
  renderGallery();
  renderBlog();
}

function renderHome() {
  const hp = document.getElementById("home-projects");
  if (hp) {
    hp.innerHTML = projects.slice(0, 2).map(p => `
      <a href="projeler.html" class="group block rounded-3xl border border-stone-200/90 bg-white overflow-hidden hover:border-emerald-500/60 hover:shadow-md transition">
        <img src="${p.img}" alt="${p[currentLang].title}" class="w-full h-52 object-cover group-hover:scale-105 transition duration-300" />
        <div class="p-6 space-y-2">
          <span class="text-xs text-emerald-700 font-semibold">${p[currentLang].course}</span>
          <h3 class="font-display font-bold text-lg text-stone-900 group-hover:text-emerald-700 transition">${p[currentLang].title}</h3>
          <p class="text-stone-600 text-xs leading-relaxed line-clamp-2">${p[currentLang].desc}</p>
        </div>
      </a>
    `).join("");
  }
  const hg = document.getElementById("home-gallery");
  if (hg) {
    hg.innerHTML = gallery.slice(0, 3).map(g => `
      <a href="galeri.html" class="group block rounded-2xl border border-stone-200/90 bg-white overflow-hidden hover:border-emerald-500/60 hover:shadow-md transition">
        <img src="${g.img}" alt="${g[currentLang].title}" class="w-full h-48 object-cover group-hover:scale-105 transition duration-300" />
        <div class="p-4">
          <p class="text-sm font-display font-bold text-stone-900">${g[currentLang].title}</p>
          <p class="text-xs text-stone-500 mt-0.5 line-clamp-1">${g[currentLang].desc}</p>
        </div>
      </a>
    `).join("");
  }
}

function filterProjects(cat) {
  activeProjFilter = cat;
  document.querySelectorAll(".pfilter-btn").forEach(btn => {
    const isAct = btn.getAttribute("data-pfilter") === cat;
    btn.className = isAct
      ? "pfilter-btn px-4 py-2 rounded-xl text-xs font-semibold bg-emerald-600 text-white shadow-sm"
      : "pfilter-btn px-4 py-2 rounded-xl text-xs font-semibold bg-white border border-stone-200 text-stone-700 hover:border-emerald-500";
  });
  renderProjects();
}

function renderProjects() {
  const list = document.getElementById("projects-list");
  if (!list) return;
  const filtered = activeProjFilter === "all" ? projects : projects.filter(p => p.cat === activeProjFilter);
  list.innerHTML = filtered.map((p, idx) => `
    <article class="grid grid-cols-1 md:grid-cols-2 gap-8 items-center bg-white border border-stone-200/90 rounded-3xl p-6 sm:p-8 shadow-sm">
      <div class="${idx % 2 === 1 ? 'md:order-2' : ''}">
        <img src="${p.img}" alt="${p[currentLang].title}" class="w-full h-64 object-cover rounded-2xl border border-stone-100" />
      </div>
      <div class="space-y-3">
        <span class="inline-block px-3 py-1 rounded-full bg-emerald-50 text-emerald-700 text-xs font-semibold">${p[currentLang].course}</span>
        <h2 class="font-display text-2xl font-bold text-stone-900">${p[currentLang].title}</h2>
        <p class="text-stone-600 text-sm leading-relaxed">${p[currentLang].desc}</p>
      </div>
    </article>
  `).join("");
}

function renderGallery() {
  const grid = document.getElementById("gallery-grid");
  if (!grid) return;
  grid.innerHTML = gallery.map((g, i) => `
    <div onclick="openLightbox(${i})" class="cursor-pointer group rounded-3xl border border-stone-200/90 bg-white overflow-hidden hover:border-emerald-500/60 hover:shadow-md transition">
      <div class="overflow-hidden">
        <img src="${g.img}" alt="${g[currentLang].title}" class="w-full h-56 object-cover group-hover:scale-105 transition duration-300" />
      </div>
      <div class="p-5 space-y-1">
        <h3 class="font-display font-bold text-base text-stone-900">${g[currentLang].title}</h3>
        <p class="text-xs text-stone-500 leading-relaxed">${g[currentLang].desc}</p>
      </div>
    </div>
  `).join("");
}

function openLightbox(idx) {
  const item = gallery[idx];
  document.getElementById("lb-img").src = item.img;
  document.getElementById("lb-title").textContent = item[currentLang].title;
  document.getElementById("lb-desc").textContent = item[currentLang].desc;
  document.getElementById("lightbox").classList.remove("hidden");
}

function closeLightbox() {
  document.getElementById("lightbox").classList.add("hidden");
}

function renderBlog() {
  const list = document.getElementById("blog-list");
  if (!list) return;

  const allCats = [...new Set(blogs.flatMap(b => b[currentLang].categories))];
  const allTags = [...new Set(blogs.flatMap(b => b[currentLang].tags))];

  const catBox = document.getElementById("blog-categories");
  catBox.innerHTML = [`all`, ...allCats].map(c => {
    const label = c === "all" ? i18n[currentLang].filter_all : c;
    const active = activeBlogCat === c;
    return `<button onclick="setBlogCat('${c}')" class="px-3 py-1 rounded-lg text-xs font-semibold transition ${active ? 'bg-emerald-600 text-white' : 'bg-stone-100 text-stone-700 hover:bg-stone-200'}">${label}</button>`;
  }).join("");

  const tagBox = document.getElementById("blog-tags");
  tagBox.innerHTML = [`all`, ...allTags].map(t => {
    const label = t === "all" ? i18n[currentLang].filter_all : `#${t}`;
    const active = activeBlogTag === t;
    return `<button onclick="setBlogTag('${t}')" class="px-2.5 py-1 rounded-lg text-xs font-medium transition ${active ? 'bg-emerald-600 text-white' : 'bg-stone-100 text-stone-600 hover:bg-stone-200'}">${label}</button>`;
  }).join("");

  const filtered = blogs.filter(b => {
    const catOk = activeBlogCat === "all" || b[currentLang].categories.includes(activeBlogCat);
    const tagOk = activeBlogTag === "all" || b[currentLang].tags.includes(activeBlogTag);
    return catOk && tagOk;
  });

  list.innerHTML = filtered.map(b => `
    <article onclick="openBlogModal(${b.id})" class="cursor-pointer rounded-3xl bg-white border border-stone-200/90 p-6 sm:p-7 hover:border-emerald-500/60 hover:shadow-md transition space-y-3">
      <div class="flex flex-wrap items-center justify-between gap-2 text-xs">
        <span class="px-3 py-1 rounded-full bg-emerald-50 text-emerald-700 font-semibold">${b[currentLang].categories.join(", ")}</span>
        <span class="text-stone-400 font-medium">${b.date}</span>
      </div>
      <h2 class="font-display text-xl sm:text-2xl font-bold text-stone-900 hover:text-emerald-700 transition">${b[currentLang].title}</h2>
      <p class="text-stone-600 text-sm leading-relaxed">${b[currentLang].excerpt}</p>
      <div class="flex flex-wrap items-center justify-between gap-2 pt-2 border-t border-stone-100">
        <div class="flex flex-wrap gap-1.5">
          ${b[currentLang].tags.map(t => `<span class="text-xs px-2.5 py-0.5 rounded-md bg-stone-100 text-stone-600">#${t}</span>`).join("")}
        </div>
        <span class="text-xs font-bold text-emerald-700">${i18n[currentLang].read_more}</span>
      </div>
    </article>
  `).join("");
}

function setBlogCat(c) { activeBlogCat = c; renderBlog(); }
function setBlogTag(t) { activeBlogTag = t; renderBlog(); }

function openBlogModal(id) {
  const b = blogs.find(item => item.id === id);
  if (!b) return;
  document.getElementById("bm-cat").textContent = b[currentLang].categories.join(" • ");
  document.getElementById("bm-title").textContent = b[currentLang].title;
  document.getElementById("bm-date").textContent = b.date;
  document.getElementById("bm-body").innerHTML = b[currentLang].content.map(p => `<p>${p}</p>`).join("");
  document.getElementById("bm-tags").innerHTML = b[currentLang].tags.map(t => `<span class="text-xs px-2.5 py-1 rounded-md bg-stone-100 text-stone-700">#${t}</span>`).join("");
  document.getElementById("blog-modal").classList.remove("hidden");
}

function closeBlogModal() {
  document.getElementById("blog-modal").classList.add("hidden");
}

function handleContactSubmit(e) {
  e.preventDefault();
  const st = document.getElementById("form-status");
  st.textContent = i18n[currentLang].form_sent;
  st.classList.remove("hidden");
  e.target.reset();
}

